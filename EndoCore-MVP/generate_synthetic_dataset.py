"""
EndoCore: Synthetic Interstitial Microenvironment Dataset Generator
===================================================================

PURPOSE
-------
Produces the SYNTHETIC training dataset used to fit the EndoCore TinyML
edge classifier. No patient data, no in-vitro data and no in-vivo data are
used anywhere in this project. Every row below is generated by this script
from published physiological ranges; the dataset is a stand-in for the
wet-lab sensor data that does not exist yet (see "What remains untested"
in README.md).

FEATURES (identical to the four signals the nanochip sensor array reads,
and identical to the four inputs exposed in the 3D simulation UI)
-----------------------------------------------------------------
  il_6_pg_ml        Interstitial IL-6                      0-100 pg/mL
  ifn_gamma_pg_ml   Interstitial IFN-gamma                 0-100 pg/mL
  ph_level          Local interstitial pH                  6.50-7.50
  cd8_tcell_count   Infiltrating CD8+ T-cells in field     0-60 cells

LITERATURE-CALIBRATED ANCHORS (as cited in the Filter 2 submission)
-------------------------------------------------------------------
  Homeostasis      IL-6 ~4 pg/mL, IFN-g ~3 pg/mL, pH 7.40, 0 CD8+ cells
  Acute attack     IL-6 40-100 pg/mL, IFN-g 40-100 pg/mL,
                   pH < 6.95 (inflammatory acidosis), 48-60 CD8+ cells
  Early Stage 1-2  Mild cytokine elevation, pH near normal, few T-cells

LABEL
-----
  ai_action = Release_Peptides  -> micro-valves should open (IL-10 / TGF-beta)
  ai_action = None              -> valves stay closed

The label is NOT a hard threshold on a single feature. A latent severity
score combines all four signals, and a stochastic term is added before
thresholding. This is deliberate: a noiseless threshold produces perfect
class separation, which drives logistic coefficients toward infinity and
yields a classifier that jumps 0% -> 100% with no usable gradient. Real
interstitial sensing is noisy, so modelling that noise is both more honest
and more useful.

USAGE
-----
  python generate_synthetic_dataset.py
Writes synthetic_cytokine_dataset.csv (deterministic; seed is fixed).
"""

import numpy as np
import pandas as pd

RANDOM_SEED = 42
N_SAMPLES = 6000

# Sensor operating ranges (match the simulation's slider bounds exactly).
IL6_RANGE = (0.0, 100.0)
IFNG_RANGE = (0.0, 100.0)
PH_RANGE = (6.50, 7.50)
TCELL_RANGE = (0, 60)

# Physiological anchors used to normalise each signal's contribution.
IL6_BASELINE, IL6_ATTACK = 4.0, 60.0
IFNG_BASELINE, IFNG_ATTACK = 3.0, 60.0
PH_BASELINE, PH_ATTACK = 7.40, 6.95
TCELL_BASELINE, TCELL_ATTACK = 0.0, 48.0

# Relative weight of each signal in the latent severity score. Cytokines
# dominate because they are the earliest and most specific indicators of an
# acute CD8+ flare; acidosis and cell count corroborate.
W_IL6, W_IFNG, W_PH, W_TCELL = 0.33, 0.33, 0.17, 0.17

SEVERITY_THRESHOLD = 0.50

# Measurement noise on the latent severity, standing in for electrochemical
# sensor noise, biological variability and the fact that cytokine levels do
# not map perfectly onto "is this an attack". Chosen so the fitted decision
# boundary stays graded across the operating range: at 0.11 the classes are
# almost perfectly separable, which drives the logistic coefficients steep
# enough that risk jumps ~0% -> ~96% over a narrow band and the model gives
# no usable early warning. At 0.20 the model still separates well (ROC-AUC
# ~0.985) while producing a progressive risk ramp.
SEVERITY_NOISE_SD = 0.20


def _unit(value, baseline, attack):
    """Scale a raw signal to roughly 0 at baseline and 1 at attack level."""
    return np.clip((value - baseline) / (attack - baseline), 0.0, 1.6)


def severity(il6, ifng, ph, tcells):
    """Latent 0-1 inflammatory severity of the local microenvironment."""
    return (
        W_IL6 * _unit(il6, IL6_BASELINE, IL6_ATTACK)
        + W_IFNG * _unit(ifng, IFNG_BASELINE, IFNG_ATTACK)
        + W_PH * _unit(PH_BASELINE - ph, 0.0, PH_BASELINE - PH_ATTACK)
        + W_TCELL * _unit(tcells, TCELL_BASELINE, TCELL_ATTACK)
    )


def _sample_states(rng, n):
    """
    Draw samples from four named physiological states plus a uniform sweep.

    The uniform sweep matters: the simulation lets a judge drag any slider to
    any value, so the classifier must be defined and sensible across the whole
    input space, not only near the four clusters.
    """
    blocks = []

    # --- Homeostasis: quiet, protected microenvironment -------------------
    k = int(n * 0.25)
    blocks.append(np.column_stack([
        rng.normal(4.0, 1.2, k).clip(*IL6_RANGE),
        rng.normal(3.0, 1.1, k).clip(*IFNG_RANGE),
        rng.normal(7.40, 0.02, k).clip(*PH_RANGE),
        rng.integers(0, 3, k),
    ]))

    # --- Early Stage 1-2: autoantibody-positive, subclinical --------------
    k = int(n * 0.15)
    blocks.append(np.column_stack([
        rng.normal(12.0, 5.0, k).clip(*IL6_RANGE),
        rng.normal(10.0, 4.5, k).clip(*IFNG_RANGE),
        rng.normal(7.33, 0.05, k).clip(*PH_RANGE),
        rng.integers(0, 14, k),
    ]))

    # --- Acute CD8+ autoimmune attack -------------------------------------
    k = int(n * 0.25)
    blocks.append(np.column_stack([
        rng.normal(72.0, 18.0, k).clip(*IL6_RANGE),
        rng.normal(70.0, 18.0, k).clip(*IFNG_RANGE),
        rng.normal(6.80, 0.13, k).clip(*PH_RANGE),
        rng.integers(40, 61, k),
    ]))

    # --- Post-modulation recovery: cytokines falling, cells clearing ------
    k = int(n * 0.10)
    blocks.append(np.column_stack([
        rng.normal(22.0, 9.0, k).clip(*IL6_RANGE),
        rng.normal(18.0, 8.0, k).clip(*IFNG_RANGE),
        rng.normal(7.22, 0.08, k).clip(*PH_RANGE),
        rng.integers(2, 22, k),
    ]))

    # --- Uniform sweep across the full sensor operating range -------------
    k = n - sum(b.shape[0] for b in blocks)
    blocks.append(np.column_stack([
        rng.uniform(*IL6_RANGE, k),
        rng.uniform(*IFNG_RANGE, k),
        rng.uniform(*PH_RANGE, k),
        rng.integers(TCELL_RANGE[0], TCELL_RANGE[1] + 1, k),
    ]))

    return np.vstack(blocks)


def build_dataset(n_samples=N_SAMPLES, seed=RANDOM_SEED):
    rng = np.random.default_rng(seed)
    x = _sample_states(rng, n_samples)
    il6, ifng, ph, tcells = x[:, 0], x[:, 1], x[:, 2], x[:, 3].astype(int)

    s = severity(il6, ifng, ph, tcells)
    noisy = s + rng.normal(0.0, SEVERITY_NOISE_SD, len(s))
    release = noisy > SEVERITY_THRESHOLD

    # Human-readable state label, for inspection only. It is NOT a feature
    # and is never shown to the classifier.
    state = np.where(
        s < 0.18, "Homeostasis",
        np.where(s < SEVERITY_THRESHOLD, "Early_AAb_Detection", "CD8_TCell_Attack"),
    )

    df = pd.DataFrame({
        "sample_id": np.arange(1, len(s) + 1),
        "il_6_pg_ml": il6.round(2),
        "ifn_gamma_pg_ml": ifng.round(2),
        "ph_level": ph.round(3),
        "cd8_tcell_count": tcells,
        "immune_state": state,
        "ai_action": np.where(release, "Release_Peptides", "None"),
    })
    return df.sample(frac=1.0, random_state=seed).reset_index(drop=True)


if __name__ == "__main__":
    data = build_dataset()
    data["sample_id"] = np.arange(1, len(data) + 1)
    data.to_csv("synthetic_cytokine_dataset.csv", index=False)

    counts = data["ai_action"].value_counts()
    print(f"Wrote synthetic_cytokine_dataset.csv  ({len(data)} rows)")
    print(f"  Release_Peptides : {counts.get('Release_Peptides', 0)}")
    print(f"  None             : {counts.get('None', 0)}")
    print("\nState distribution:")
    print(data["immune_state"].value_counts().to_string())
