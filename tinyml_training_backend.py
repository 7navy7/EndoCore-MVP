"""
EndoCore: TinyML Edge-AI Training Backend
=========================================

Trains the lightweight classifier that the EndoCore nanochip's Layer 4
edge-AI processor would run, and EXPORTS THE FITTED PARAMETERS so that the
browser-based digital twin (index.html) runs this exact model rather than a
hand-tuned formula.

Pipeline
--------
    generate_synthetic_dataset.py  ->  synthetic_cytokine_dataset.csv
    tinyml_training_backend.py     ->  endocore_model.json
                                       endocore_model.js   (loaded by the page)
                                       validation_report.txt

Why logistic regression
-----------------------
The target hardware is a microcontroller inside a sealed implant. Inference
must be deterministic, auditable and cheap. A logistic model is four
multiply-adds and one exponential: it fits in a few hundred bytes of flash
and runs in microseconds, far inside the <50 ms budget claimed for Layer 4.
A tree ensemble would be larger, harder to audit, and would produce the
step-function output that is wrong for a dosing decision - we want a
graded risk probability, not a hard yes/no.

Feature vector (4 signals, matching the sensor array and the simulation UI)
---------------------------------------------------------------------------
    il_6_pg_ml        raw
    ifn_gamma_pg_ml   raw
    ph_drop           engineered: max(0, 7.40 - measured pH)
                      (a RISE in acidity is the inflammatory signal, so the
                      drop below physiological pH is the meaningful quantity)
    cd8_tcell_count   raw

IMPORTANT - SCOPE OF THESE RESULTS
----------------------------------
The metrics below are measured on SYNTHETIC data generated by
generate_synthetic_dataset.py. They demonstrate that the closed-loop control
logic is internally consistent and that the decision boundary behaves
sensibly across the sensor operating range. They are NOT evidence of
biological efficacy, and they are NOT a substitute for wet-lab validation.
See "What remains untested" in README.md.

Usage
-----
    python tinyml_training_backend.py
"""

import json

import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (
    classification_report,
    confusion_matrix,
    roc_auc_score,
)
from sklearn.model_selection import StratifiedKFold, cross_val_score, train_test_split

DATASET = "synthetic_cytokine_dataset.csv"
MODEL_JSON = "endocore_model.json"
MODEL_JS = "endocore_model.js"
REPORT = "validation_report.txt"

PH_REFERENCE = 7.40          # physiological interstitial pH
DECISION_THRESHOLD = 0.35    # >= 35% predicted risk -> open the micro-valves
FEATURES = ["il_6_pg_ml", "ifn_gamma_pg_ml", "ph_drop", "cd8_tcell_count"]
RANDOM_SEED = 42


def load_features(path=DATASET):
    df = pd.read_csv(path)
    df["ph_drop"] = (PH_REFERENCE - df["ph_level"]).clip(lower=0.0)
    x = df[FEATURES].to_numpy(dtype=float)
    y = (df["ai_action"] == "Release_Peptides").to_numpy(dtype=int)
    return df, x, y


def main():
    lines = []

    def say(text=""):
        print(text)
        lines.append(text)

    say("Loading synthetic in-vitro cytokine dataset...")
    df, x, y = load_features()
    say(f"  {len(df)} samples | {int(y.sum())} release / {int((1 - y).sum())} no-release")
    say(f"  Features: {', '.join(FEATURES)}")
    say()

    x_train, x_test, y_train, y_test = train_test_split(
        x, y, test_size=0.25, random_state=RANDOM_SEED, stratify=y
    )

    say("Training TinyML logistic classifier for nanochip deployment...")
    model = LogisticRegression(max_iter=5000, random_state=RANDOM_SEED)
    model.fit(x_train, y_train)

    # --- Cross-validation on the training split ---------------------------
    cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=RANDOM_SEED)
    cv_acc = cross_val_score(model, x_train, y_train, cv=cv, scoring="accuracy")
    cv_auc = cross_val_score(model, x_train, y_train, cv=cv, scoring="roc_auc")
    say(f"  5-fold CV accuracy : {cv_acc.mean():.4f} +/- {cv_acc.std():.4f}")
    say(f"  5-fold CV ROC-AUC  : {cv_auc.mean():.4f} +/- {cv_auc.std():.4f}")
    say()

    # --- Held-out evaluation at the deployed decision threshold -----------
    proba = model.predict_proba(x_test)[:, 1]
    pred = (proba >= DECISION_THRESHOLD).astype(int)

    tn, fp, fn, tp = confusion_matrix(y_test, pred).ravel()
    sensitivity = tp / (tp + fn)
    specificity = tn / (tn + fp)
    precision = tp / (tp + fp)
    npv = tn / (tn + fn)
    accuracy = (tp + tn) / len(y_test)
    auc = roc_auc_score(y_test, proba)

    say("--- EndoCore AI Validation Metrics (held-out test set, synthetic) ---")
    say(f"  Decision threshold : {DECISION_THRESHOLD:.2f} predicted risk")
    say(f"  Test samples       : {len(y_test)}")
    say()
    say("  Confusion matrix")
    say("                      predicted None   predicted Release")
    say(f"    actual None       {tn:>14}   {fp:>17}")
    say(f"    actual Release    {fn:>14}   {tp:>17}")
    say()
    say(f"  Sensitivity (recall, attack detected) : {sensitivity:.4f}")
    say(f"  Specificity (quiet state preserved)   : {specificity:.4f}")
    say(f"  Precision (PPV)                       : {precision:.4f}")
    say(f"  Negative predictive value             : {npv:.4f}")
    say(f"  Accuracy                              : {accuracy:.4f}")
    say(f"  ROC-AUC                               : {auc:.4f}")
    say()
    say("  Per-class report")
    for line in classification_report(
        y_test, pred, target_names=["None", "Release_Peptides"], zero_division=0
    ).splitlines():
        say("    " + line)
    say()

    # --- Sanity probes at the scenarios the 3D demo actually plays --------
    probes = [
        ("Homeostasis (baseline)",        4.0,   3.0, 7.40,  0),
        ("Early Stage 1-2 infiltration", 14.0,  12.0, 7.32,  8),
        ("Mid-ramp flare",               45.0,  42.0, 7.10, 30),
        ("Acute attack peak",            98.0, 100.0, 6.55, 60),
    ]
    say("--- Predicted risk at key simulation states ---")
    for name, il6, ifng, ph, tcells in probes:
        vec = np.array([[il6, ifng, max(0.0, PH_REFERENCE - ph), tcells]])
        p = model.predict_proba(vec)[0, 1] * 100
        action = "RELEASE" if p >= DECISION_THRESHOLD * 100 else "closed "
        say(f"  {name:<28} {p:6.2f}%   valves {action}")
    say()

    # --- Export for the browser digital twin ------------------------------
    coefs = dict(zip(FEATURES, model.coef_[0].tolist()))
    payload = {
        "model_type": "logistic_regression",
        "trained_on": DATASET,
        "data_provenance": "synthetic; generated by generate_synthetic_dataset.py",
        "n_samples": int(len(df)),
        "features": FEATURES,
        "ph_reference": PH_REFERENCE,
        "intercept": float(model.intercept_[0]),
        "coefficients": coefs,
        "decision_threshold": DECISION_THRESHOLD,
        "validation": {
            "scope": "synthetic data only; not evidence of biological efficacy",
            "cv_accuracy_mean": float(cv_acc.mean()),
            "cv_roc_auc_mean": float(cv_auc.mean()),
            "test_sensitivity": float(sensitivity),
            "test_specificity": float(specificity),
            "test_precision": float(precision),
            "test_accuracy": float(accuracy),
            "test_roc_auc": float(auc),
            "confusion_matrix": {
                "true_negative": int(tn), "false_positive": int(fp),
                "false_negative": int(fn), "true_positive": int(tp),
            },
        },
    }

    with open(MODEL_JSON, "w") as f:
        json.dump(payload, f, indent=2)

    # A plain .js file (not .json) so the page works when opened directly
    # from disk as well as over HTTP - file:// blocks fetch(), not <script>.
    with open(MODEL_JS, "w") as f:
        f.write("// AUTO-GENERATED by tinyml_training_backend.py - do not edit by hand.\n")
        f.write("// Fitted logistic coefficients for the EndoCore Layer 4 edge classifier.\n")
        f.write("// Trained on SYNTHETIC data; see README.md for scope and limitations.\n")
        f.write("window.ENDOCORE_MODEL = ")
        json.dump(payload, f, indent=2)
        f.write(";\n")

    say(f"Exported fitted parameters -> {MODEL_JSON}")
    say(f"Exported browser model     -> {MODEL_JS}  (loaded by index.html)")
    say(f"Validation report          -> {REPORT}")

    with open(REPORT, "w") as f:
        f.write("\n".join(lines) + "\n")

    return model


if __name__ == "__main__":
    main()
